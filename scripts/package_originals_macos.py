"""CTest geçmiş F-Kick/F-TransForm derlemesini, tam kaynaklarıyla paketler."""
from pathlib import Path
import argparse
import hashlib
import json
import os
import plistlib
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import zipfile


def run(*args):
    return subprocess.check_output(args, text=True).strip()


def digest(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def source_files(base):
    for path in sorted(base.rglob('*')):
        if path.is_file() and not any(part in {'.git', '__pycache__', '.vs', 'build', 'build-macos', 'build-linux'}
                                      for part in path.relative_to(base).parts[:-1]):
            yield path


def put_tree(archive, base, prefix):
    for path in source_files(base):
        archive.write(path, (Path(prefix) / path.relative_to(base)).as_posix())


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('project')
    args = parser.parse_args()
    if sys.platform != 'darwin':
        raise RuntimeError('Package on the native macOS build host')
    root = Path(args.project).resolve()
    lock = json.loads((root / 'source-lock.json').read_text(encoding='utf-8-sig'))
    name, version = lock['product'], lock['version']
    target = {'F-Kick': 'FKick', 'F-TransForm': 'FTransForm'}[name]
    cmake = (root / 'CMakeLists.txt').read_text(encoding='utf-8-sig')
    assert re.search(r'project\(' + target + r' VERSION ' + re.escape(version) + r'\b', cmake)
    build = root / 'build-macos'
    log = build / 'Testing/Temporary/LastTest.log'
    tests = log.read_text(errors='replace')
    assert 'Test Passed.' in tests and 'Test Failed.' not in tests, 'CTest must pass'
    artefacts = build / (target + '_artefacts/Release')
    bundles = [('VST3', artefacts / ('VST3/' + name + '.vst3')),
               ('AU', artefacts / ('AU/' + name + '.component')),
               ('Standalone', artefacts / ('Standalone/' + name + '.app'))]
    # Her paketin gerçek Mach-O dosyasında iki mimariyi ve sürümü doğrula.
    checks = []
    for kind, bundle in bundles:
        assert bundle.is_dir(), f'Missing {kind}: {bundle}'
        with (bundle / 'Contents/Info.plist').open('rb') as stream:
            info = plistlib.load(stream)
        assert info['CFBundleShortVersionString'] == version, 'Stale bundle version'
        executable = bundle / 'Contents/MacOS' / info['CFBundleExecutable']
        architectures = run('lipo', '-archs', str(executable)).split()
        assert set(architectures) == {'arm64', 'x86_64'}, architectures
        # Developer ID anahtarı bulunmadığından açıkça ad-hoc imzalanır.
        subprocess.run(['codesign', '--force', '--deep', '--sign', '-', str(bundle)], check=True)
        subprocess.run(['codesign', '--verify', '--deep', '--strict', str(bundle)], check=True)
        checks.append({'format': kind, 'architectures': architectures,
                       'version': info['CFBundleShortVersionString'], 'signature': 'ad-hoc'})
    juce = root / 'Dependencies/JUCE'
    assert (juce / 'CMakeLists.txt').is_file(), 'Complete pinned JUCE source required'
    fonts = root / 'vendor/urw-base35-fonts'
    if name == 'F-TransForm':
        assert (fonts / 'fonts/URWGothic-Book.otf').is_file()
        for local, upstream in [('Book.otf', 'URWGothic-Book.otf'), ('Demi.otf', 'URWGothic-Demi.otf')]:
            assert digest(root / 'Resources/fonts' / local) == digest(fonts / 'fonts' / upstream)
    out = root / 'dist/macos-release'
    out.mkdir(parents=True, exist_ok=True)
    source = out / f'{name}-{version}-macOS-Source.zip'
    instructions = '''macOS Universal build — Fazıl Irak
Requires macOS, Xcode command line tools, Python 3.12+, CMake 3.24+ and Ninja.
The complete pinned JUCE source is included in Dependencies/JUCE.
cmake -S . -B build-macos -G Ninja -DCMAKE_BUILD_TYPE=Release '-DCMAKE_OSX_ARCHITECTURES=arm64;x86_64' -DCMAKE_OSX_DEPLOYMENT_TARGET=11.0
cmake --build build-macos --parallel 3
ctest --test-dir build-macos --output-on-failure --timeout 600
python3 release-tools/package_originals_macos.py .
VST3, AU and Standalone are generated by the existing Apple CMake targets.
Parameter/plugin IDs and preset/session formats are unchanged.
'''
    # Sadece dağıtım için gerekli uygulama, test, kaynak ve lisanslar alınır;
    # bağımlılıkların tamamı eklenir, SDK dosyaları yalnızca bağlantı olarak bırakılmaz.
    with zipfile.ZipFile(source, 'w', zipfile.ZIP_DEFLATED) as archive:
        for part in ['Source', 'Tests', 'scripts', 'Resources', 'licenses', 'docs']:
            if (root / part).is_dir():
                put_tree(archive, root / part, part)
        for part in ['CMakeLists.txt', 'AGENTS.md', 'README.md', 'AUTHORS.md',
                     'LICENSE', 'LICENSE.txt', 'JUCE-LICENSE.md', 'THIRD-PARTY-NOTICES.txt',
                     '.gitignore', 'source-lock.json', 'preview.png', 'preview-about.png']:
            if (root / part).is_file():
                archive.write(root / part, part)
        put_tree(archive, juce, 'Dependencies/JUCE')
        if name == 'F-TransForm':
            put_tree(archive, fonts, 'vendor/urw-base35-fonts')
            archive.write(fonts.parent / 'URW-VERIFIED.json', 'vendor/URW-VERIFIED.json')
        archive.write(Path(__file__).resolve(), 'release-tools/package_originals_macos.py')
        archive.writestr('BUILD-MACOS.txt', instructions)
        archive.write(log, 'validation/CTest-macOS.txt')
    with zipfile.ZipFile(source) as archive:
        assert archive.testzip() is None
        for part in ['CMakeLists.txt', 'Dependencies/JUCE/CMakeLists.txt', 'AUTHORS.md', 'BUILD-MACOS.txt']:
            assert part in archive.namelist(), part
    binary = out / f'{name}-{version}-macOS-Universal.tar.gz'
    with tempfile.TemporaryDirectory() as temporary:
        package = Path(temporary) / f'{name}-{version}-macOS-Universal'
        package.mkdir()
        for kind, bundle in bundles:
            shutil.copytree(bundle, package / kind / bundle.name, symlinks=True)
        for part in ['LICENSE', 'LICENSE.txt', 'THIRD-PARTY-NOTICES.txt', 'AUTHORS.md', 'preview.png', 'preview-about.png']:
            if (root / part).is_file():
                shutil.copy2(root / part, package / part)
        shutil.copytree(root / 'licenses', package / 'licenses')
        shutil.copy2(log, package / 'TEST-RESULTS.txt')
        (package / 'INSTALL.txt').write_text(
            f'{name} {version} — FAZIL IRAK\nmacOS 11.0+; Apple Silicon + Intel Universal.\n'
            'Copy the complete VST3 bundle to ~/Library/Audio/Plug-Ins/VST3/ and the AU component to ~/Library/Audio/Plug-Ins/Components/. Rescan your host.\n'
            'Standalone contains the independent application. Bundles are ad-hoc signed, not Apple notarised or Developer ID signed.\n'
            'CTest ran on the native macOS CI host; independent DAW and physical Intel Mac testing remains separate.\n'
            f'Complete corresponding source: {source.name}\nhttps://github.com/fazilirak/Music/releases/tag/{name}-v{version}\n', encoding='utf-8')
        # tarfile korumalı sembolik bağları ve Mach-O yürütme izinlerini saklar.
        with tarfile.open(binary, 'w:gz') as archive:
            archive.add(package, arcname=package.name)
    manifest = {'product': name, 'developer': 'Fazıl Irak', 'version': version,
                'platform': 'macOS Universal', 'minimum_macos': '11.0',
                'source_commit': os.environ.get('GITHUB_SHA'), 'juce_commit': lock['juceCommit'],
                'tests': 'Native macOS CTest passed; physical Intel Mac and third-party DAW testing not performed',
                'bundles': checks, 'sha256': {path.name: digest(path) for path in [binary, source]}}
    (out / 'macOS-RELEASE-MANIFEST.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(manifest, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
