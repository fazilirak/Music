struct Hit {double start,length,level;};
inline Shape gates(std::initializer_list<Hit> hits,bool soft=false){
 Shape s;
 auto add=[&](Node n){if(!s.empty()&&std::abs(s.back().x-n.x)<1e-8)s.back()=n;else s.push_back(n);};
 add({0,0});
 for(auto h:hits){const double attack=juce::jmin(.012,h.length*.12),release=juce::jmin(.045,h.length*.3);
  add({h.start,0,soft?.10:-.25,soft?2:1});add({h.start+attack,h.level});
  add({h.start+h.length-release,h.level,soft?.15:.27,soft?2:1});add({h.start+h.length,0});
 }add({1,0});return s;
}
