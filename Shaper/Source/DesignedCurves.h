inline juce::String encode(const Shape& nodes,float depth=1,bool bipolar=false,bool tailFlag=false){
 juce::String text;
 for(auto p:nodes){double v=bipolar?.5+(p.v-.5)*depth:1-depth+depth*p.v;
  text+=juce::String(p.x,9)+" "+juce::String(1.-juce::jlimit(0.,1.,v),9)+" "+juce::String(p.t,9)+" "+juce::String(p.type)+(tailFlag?" 0 ":" ");}
 return text;
}
