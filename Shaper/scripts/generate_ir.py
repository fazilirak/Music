"""Generate Shaper's synthetic four-channel IR without recordings or external data."""
from pathlib import Path
import hashlib
import json
import math
import struct
import wave

ROOT = Path(__file__).resolve().parents[1]


def generate():
    rate, frames = 48000, 96000
    channels = []
    for channel in range(4):
        seed = 0x53485052 + channel * 7919
        filtered = 0.0
        values = []
        cross = channel in (1, 2)
        delay = int(rate * (0.019 if cross else 0.012)) + channel * 53
        for frame in range(frames):
            seed = (1664525 * seed + 1013904223) & 0xffffffff
            noise = seed / 2147483648.0 - 1.0
            filtered += 0.32 * (noise - filtered)
            age = (frame - delay) / rate
            value = 0.0
            if age >= 0:
                onset = min(1.0, age / 0.035)
                value = filtered * onset * math.exp(-math.log(1000) * age / 1.6)
                value *= 0.028 if cross else 0.04
            values.append(value)
        for milliseconds, gain in ((0, 0.28), (13, -0.18), (31, 0.13), (57, -0.09)):
            values[delay + int(rate * milliseconds / 1000)] += gain * (0.6 if cross else 1.0)
        channels.append(values)
    data = bytearray()
    for frame in range(frames):
        for channel in range(4):
            value = max(-32767, min(32767, round(channels[channel][frame] * 32767)))
            data.extend(struct.pack('<h', value))
    target = ROOT / 'Resources/impulses/Shaper_Hall_Quad.wav'
    target.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(target), 'wb') as output:
        output.setnchannels(4)
        output.setsampwidth(2)
        output.setframerate(rate)
        output.writeframes(data)
    manifest = {
        'file': target.relative_to(ROOT).as_posix(),
        'copyright': 'Copyright (c) 2026 Fazıl Irak',
        'license': 'GPL-3.0-only',
        'origin': 'Synthetic noise decay and discrete reflections generated by scripts/generate_ir.py; no external recordings or IR data.',
        'channels': ['LL', 'LR', 'RL', 'RR'], 'sample_rate': rate, 'frames': frames,
        'sha256': hashlib.sha256(target.read_bytes()).hexdigest(),
    }
    (target.parent / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(manifest['file'], manifest['sha256'])


if __name__ == '__main__':
    generate()
